import { test, expect } from '@playwright/test'
import { courses } from '../src/data/courses'

test('uses editorial themes and a responsive, keyboard-accessible course manual', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(15, 15, 15)')
  await page.screenshot({ path: testInfo.outputPath('editorial-dark.png'), fullPage: true })
  await page.getByTestId('theme-toggle').click()
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(245, 241, 233)')
  await page.screenshot({ path: testInfo.outputPath('editorial-light.png'), fullPage: true })
  await page.getByRole('button', { name: 'Abrir cursos', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'cursos', exact: true })
  const reader = dialog.getByRole('group', { name: 'cursos' })
  await expect(reader.getByRole('article')).toHaveCount(1)
  await expect(reader.getByRole('button', { name: 'Página anterior' })).toBeDisabled()
  await expect(reader.getByRole('link', { name: 'Ver curso →' })).toHaveAttribute('href', courses[0]!.url)
  await reader.focus()
  await page.keyboard.press('End')
  await expect(reader.getByRole('button', { name: 'Página siguiente' })).toBeDisabled()
  await expect(reader.getByRole('link', { name: 'Ver curso →' })).toHaveAttribute('href', courses.at(-1)!.url)
  await page.keyboard.press('Home')
  await reader.getByLabel('Ir a página').selectOption('1')
  await expect(reader.getByRole('link', { name: 'Ver curso →' })).toHaveAttribute('href', courses[1]!.url)
  const contents = reader.locator('.manual-contents')
  await expect(contents).toHaveCSS('display', page.viewportSize()!.width <= 820 ? 'none' : 'block')
  expect(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true)
  expect(await reader.evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('course-manual.png') })
  await reader.getByRole('button', { name: 'Ver todo' }).click()
  await expect(reader.getByRole('article')).toHaveCount(courses.length)
  expect(await reader.getByRole('link').evaluateAll((links) => links.map((link) => link.getAttribute('href'))))
    .toEqual(courses.flatMap((course) => [course.url, course.repo]))
  await dialog.getByRole('button', { name: 'Cerrar cursos' }).click()
  await expect(page.getByRole('button', { name: 'Abrir cursos', exact: true })).toBeFocused()
})

test('prints every manual record, restores book state and preserves English controls', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('language-toggle').click()
  await page.getByRole('button', { name: 'Open courses', exact: true }).click()
  const reader = page.getByRole('group', { name: 'courses' })
  await reader.getByRole('button', { name: 'Next page' }).click()
  await expect(reader.getByRole('article')).toHaveCount(1)
  await page.evaluate(() => window.dispatchEvent(new Event('beforeprint')))
  await page.emulateMedia({ media: 'print' })
  for (const title of courses.map((course) => course.title)) {
    await expect(page.locator('#cursos .manual-page').filter({ hasText: title }).first()).toBeVisible()
  }
  await page.emulateMedia({ media: 'screen' })
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')))
  await expect(page.getByRole('dialog', { name: 'courses', exact: true })).toBeVisible()
  await expect(reader.getByRole('article')).toHaveCount(1)
  await expect(reader.getByRole('link', { name: 'View course →' })).toHaveAttribute('href', courses[1]!.url)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Open courses', exact: true })).toBeFocused()
})

test('opens certificates as records without inventing proof links', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Abrir certificaciones', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'certificaciones', exact: true })
  const reader = dialog.getByRole('group', { name: 'certificaciones' })
  await expect(reader.getByRole('article')).toHaveCount(1)
  const total = await reader.getByLabel('Ir a página').locator('option').count()
  expect(total).toBeGreaterThan(0)
  await reader.getByRole('button', { name: 'Ver todo' }).click()
  await expect(reader.getByRole('article')).toHaveCount(total)
  await expect(reader.getByRole('link')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('certification-manual.png') })
})
